#!/usr/bin/env node
// Exports generated posts (from real PlacidWay pages) to samples/README.md + images.
import { execSync } from 'node:child_process';
import { writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';

const sql = `SELECT coalesce(json_agg(p ORDER BY p.id), '[]') FROM (
  SELECT id, source_url, content_type, category, title, post_text, media_path, attempts, status, dry_run, fb_permalink, guardrail, claims, created_at
  FROM posts WHERE post_text IS NOT NULL) p`;
const rows = JSON.parse(execSync(`docker compose exec -T postgres psql -U pw -d pw -tAc "${sql.replace(/\n/g, ' ')}"`).toString());
mkdirSync('samples/images', { recursive: true });

const outcome = (p) => p.fb_permalink && !p.dry_run ? `**live on Facebook**: [view post](${p.fb_permalink})`
  : ['published', 'scheduled'].includes(p.status) ? `${p.status} (dry run, simulated)` : p.status.replace('_', ' ');
const TYPE = { article: 'Patient guide (article)', package: 'Treatment package', answer: 'Patient Q&A', news: 'News' };
let md = `# Sample output: posts generated from real PlacidWay pages

Generated by the live pipeline on ${new Date().toISOString().slice(0, 10)} (Claude Sonnet writer, Claude Haiku reviewer).
Each entry shows the source page, the final post exactly as it would be published, the branded image, and the guardrail outcome.
Exported with \`node tools/export-samples.mjs\`.

| # | Type | Source | Attempts | Guardrails | Outcome |
|---|---|---|---|---|---|
`;
for (const p of rows) {
  const g = p.guardrail || {};
  md += `| ${p.id} | ${TYPE[p.content_type] || p.content_type} | [${p.title.replace(/\|/g, '/')}](${p.source_url}) | ${p.attempts} | ${g.passed ? '✅ passed' : '⚠️ needs review'} | ${outcome(p)} |\n`;
}
for (const p of rows) {
  const g = p.guardrail || {};
  const img = p.media_path && existsSync(p.media_path) ? `images/post-${p.id}.jpg` : null;
  if (img) copyFileSync(p.media_path, `samples/${img}`);
  const failedFirst = (g.attempts_log || []).filter((a) => !a.passed);
  md += `\n---\n\n## ${p.id}. ${p.title}\n\n`;
  md += `- **Outcome:** ${outcome(p)}\n- **Source:** ${p.source_url}\n- **Type / category:** ${TYPE[p.content_type] || p.content_type} · ${p.category}\n`;
  md += `- **Why selected:** ${g.selection?.reason || '—'}\n`;
  md += `- **Guardrails:** ${(g.rules?.checks || []).filter((c) => c.pass).length}/${(g.rules?.checks || []).length} rules passed · AI reviewer: ${g.llm?.verdict || '—'} · ${p.attempts} attempt(s)\n`;
  if (failedFirst.length) md += `- **Caught and fixed:** attempt ${failedFirst.map((a) => `${a.attempt} failed ${[...(a.failed_rules || []), a.llm_verdict === 'fail' ? 'AI review' : null].filter(Boolean).join(', ')}`).join('; ')}; rewritten with feedback\n`;
  md += `\n\`\`\`text\n${p.post_text}\n\`\`\`\n\n`;
  if (img) md += `![Branded image for post ${p.id}](${img})\n\n`;
  if ((p.claims || []).length) {
    md += `<details><summary>Grounding: each line's supporting quote from the source</summary>\n\n| Post line | Verbatim source quote |\n|---|---|\n`;
    for (const c of p.claims) md += `| ${c.line.replace(/\|/g, '/')} | “${c.source_quote.replace(/\|/g, '/').replace(/\n/g, ' ')}” |\n`;
    md += `\n</details>\n`;
  }
  if (g.llm?.summary) md += `\n> **AI reviewer:** ${g.llm.summary}\n`;
}
writeFileSync('samples/README.md', md);
console.log(`exported ${rows.length} posts to samples/README.md`);
